setup_upf() {
  apt_install_common
  install_ofed_userspace
  load_rdma_modules
  validate_rdma_stack
  configure_hugepages

  configure_ip "${N3_IF}" "${UPF_N3_IP}/24" "UPF N3/access"
  configure_ip "${N6_IF}" "${UPF_N6_IP}/24" "UPF N6/core"
  configure_ip "${CTRL_IF}" "${UPF_CTRL_IP}/24" "UPF PFCP/control"
  persist_netplan_for_role
  basic_reachability_tests

  log "Cloning OMEC repositories if needed"
  mkdir -p "${BESS_WORKDIR}"
  cd "${BESS_WORKDIR}"
  [[ -d upf ]] || git clone https://github.com/omec-project/upf.git
  [[ -d bess ]] || git clone https://github.com/omec-project/bess.git

  log "Building BESS-UPF Docker images"
  cd "${BESS_WORKDIR}/upf"
  make DOCKER_BUILD_ARGS="--network=host" docker-build

  setup_upf_configs

  log "Building mlx5-enabled BESS image"
  cd "${BESS_WORKDIR}/config"
  docker build --network=host -f Dockerfile.bess-mlx5 -t upf-bess:2.4.2-dev-mlx5 .

  local rx_mac
  rx_mac="$(discover_neighbor_mac "${N6_IF}" "${RECEIVER_N6_IP}" "${RECEIVER_N6_MAC}")"
  if [[ -z "${rx_mac}" ]]; then
    warn "Could not discover receiver N6 MAC. Re-run with --receiver-n6-mac MAC before starting experiments."
  else
    log "Installing static N6 neighbor and route to receiver ${RECEIVER_N6_IP}, MAC ${rx_mac}"
    ip neigh replace "${RECEIVER_N6_IP}" lladdr "${rx_mac}" dev "${N6_IF}" nud permanent
    ip route replace "${RECEIVER_N6_IP}/32" via "${RECEIVER_N6_IP}" dev "${N6_IF}" onlink
  fi

  if [[ "${START_UPF}" == "true" ]]; then
    log "Starting BESS-UPF DPDK containers"
    cd "${BESS_WORKDIR}/config"
    docker rm -f pfcpiface bess-routectl bess 2>/dev/null || true
    docker compose -f docker-compose-dpdk.yml up -d bess
    sleep 3
    docker logs bess --tail 80 || true

    log "Loading UPF pipeline"
    docker exec bess bash -lc 'cd /opt/bess/bessctl && ./bessctl run up4'

    log "Starting pfcpiface"
    docker compose -f docker-compose-dpdk.yml up -d pfcpiface

    log "Starting route controller"
    docker rm -f bess-routectl 2>/dev/null || true
    docker run --name bess-routectl -td --restart unless-stopped \
      --net host \
      --pid container:bess \
      --entrypoint python3 \
      -v "${BESS_WORKDIR}/upf/conf/route_control.py:/route_control.py" \
      upf-bess:2.4.2-dev-mlx5 \
      /route_control.py -i "${N3_IF}" "${N6_IF}"

    sleep 3
    docker logs bess-routectl --tail 30 || true
  fi

  cat > "${BESS_WORKDIR}/config/README-next-commands.txt" <<EOF_UPF_NEXT
UPF host prepared.

Interfaces:
  N3/access:      ${N3_IF}, ${UPF_N3_IP}, MAC $(iface_mac "${N3_IF}"), PCI $(iface_pci_short "${N3_IF}")
  N6/core:        ${N6_IF}, ${UPF_N6_IP}, MAC $(iface_mac "${N6_IF}"), PCI $(iface_pci_short "${N6_IF}")
  PFCP/control:  ${CTRL_IF}, ${UPF_CTRL_IP}, MAC $(iface_mac "${CTRL_IF}")

Use this UPF N3 MAC on the TRex host if ARP discovery is not available:
  --upf-n3-mac $(iface_mac "${N3_IF}")

After you start your patched pfcpsim on the TRex host, configure it with:
  pfcpctl -s localhost:12345 service configure --n3-addr ${UPF_N3_IP} --remote-peer-addr ${UPF_CTRL_IP}
  pfcpctl -s localhost:12345 service associate

Then create sessions using your patched per-slice MBR flags.

Validation:
  curl -s http://127.0.0.1:8080/metrics | grep pfcp_sessions
  docker exec bess /opt/bess/bessctl/bessctl show port
  docker exec bess /opt/bess/bessctl/bessctl show module ${N6_IF}Routes
EOF_UPF_NEXT

  log "UPF setup complete"
  cat "${BESS_WORKDIR}/config/README-next-commands.txt"
}

setup_trex_profile_dir() {
  mkdir -p "${TREX_DIR}/automation/preof"
  cat > "${TREX_DIR}/automation/preof/README.txt" <<EOF_TREX_README
TRex host prepared.

This setup intentionally does not clone pfcpsim.
Use your patched repository or image.

Typical patched pfcpsim startup:
  sudo docker run --rm -d --network host --name pfcpsim pfcpsim:patched -p 12345 --interface ${CTRL_IF}

Typical PFCP configuration:
  sudo docker exec pfcpsim pfcpctl -s localhost:12345 service configure --n3-addr ${UPF_N3_IP} --remote-peer-addr ${UPF_CTRL_IP}
  sudo docker exec pfcpsim pfcpctl -s localhost:12345 service associate
EOF_TREX_README
}

write_trex_cfg() {
  local n3_pci n3_src_mac dest_mac
  n3_pci="$(iface_pci_short "${N3_IF}")"
  n3_src_mac="$(iface_mac "${N3_IF}")"

  dest_mac="$(discover_neighbor_mac "${N3_IF}" "${UPF_N3_IP}" "${UPF_N3_MAC}")"
  if [[ -z "${dest_mac}" ]]; then
    fatal "Could not discover UPF N3 MAC. Re-run with --upf-n3-mac MAC."
  fi

  if [[ -n "${TREX_PORT2_IF}" ]]; then
    interface_exists "${TREX_PORT2_IF}" || fatal "Optional TRex port2 interface ${TREX_PORT2_IF} not found"
    [[ -n "${TREX_PORT2_DST_MAC}" ]] || fatal "When using --trex-port2-if, also pass --trex-port2-dst-mac"
    local p2_pci p2_src_mac
    p2_pci="$(iface_pci_short "${TREX_PORT2_IF}")"
    p2_src_mac="$(iface_mac "${TREX_PORT2_IF}")"
    cat > /etc/trex_cfg.yaml <<EOF_TREX_CFG2
- version: 2
  interfaces: ['${n3_pci}', '${p2_pci}']
  port_mtu: 1500
  port_info:
      - dest_mac: ${dest_mac}
        src_mac:  ${n3_src_mac}
      - dest_mac: ${TREX_PORT2_DST_MAC}
        src_mac:  ${p2_src_mac}

  platform:
      master_thread_id: 0
      latency_thread_id: 1
      dual_if:
        - socket: 0
          threads: [2,3,4,5,6,7,8,9]
EOF_TREX_CFG2
  else
    cat > /etc/trex_cfg.yaml <<EOF_TREX_CFG1
- version: 2
  interfaces: ['${n3_pci}']
  port_mtu: 1500
  port_info:
      - dest_mac: ${dest_mac}
        src_mac:  ${n3_src_mac}

  platform:
      master_thread_id: 0
      latency_thread_id: 1
      dual_if:
        - socket: 0
          threads: [2,3,4,5,6,7,8,9]
EOF_TREX_CFG1
  fi

  log "Generated /etc/trex_cfg.yaml"
  cat /etc/trex_cfg.yaml

  if [[ -z "${TREX_PORT2_IF}" ]]; then
    warn "Generated a one-port TRex configuration. If your TRex binary refuses one port, rerun with --trex-port2-if enp8s0np0 and a valid --trex-port2-dst-mac."
  fi
}

setup_trex() {
  apt_install_common
  install_ofed_userspace
  load_rdma_modules
  validate_rdma_stack
  configure_hugepages

  configure_ip "${N3_IF}" "${TREX_N3_IP}/24" "TRex N3"
  configure_ip "${CTRL_IF}" "${TREX_CTRL_IP}/24" "TRex PFCP/control"
  if [[ -n "${TREX_PORT2_IF}" ]]; then
    ip link set "${TREX_PORT2_IF}" up
    ip link set "${TREX_PORT2_IF}" mtu 1500
  fi
  persist_netplan_for_role
  basic_reachability_tests

  log "Installing TRex ${TREX_VERSION}"
  mkdir -p /opt/trex /tmp/preof-trex
  cd /tmp/preof-trex
  if [[ ! -f "${TREX_VERSION}.tar.gz" ]]; then
    wget --no-check-certificate -O "${TREX_VERSION}.tar.gz" "${TREX_TARBALL_URL}"
  fi
  tar -xzf "${TREX_VERSION}.tar.gz" -C /opt/trex
  test -x "${TREX_DIR}/t-rex-64" || fatal "TRex binary not found at ${TREX_DIR}/t-rex-64"

  modprobe ib_uverbs || true
  modprobe rdma_ucm || true
  modprobe mlx5_ib || true

  write_trex_cfg
  setup_trex_profile_dir

  cat > "${TREX_DIR}/automation/preof/host-summary.txt" <<EOF_TREX_SUMMARY
TRex host prepared.

N3 interface:      ${N3_IF}, ${TREX_N3_IP}, MAC $(iface_mac "${N3_IF}"), PCI $(iface_pci_short "${N3_IF}")
PFCP/control:      ${CTRL_IF}, ${TREX_CTRL_IP}, MAC $(iface_mac "${CTRL_IF}")
TRex config:       /etc/trex_cfg.yaml
TRex directory:    ${TREX_DIR}

Start TRex:
  cd ${TREX_DIR}
  sudo ./t-rex-64 -i --no-ofed-check -c 8

For software latency mode:
  cd ${TREX_DIR}
  sudo ./t-rex-64 -i --software --no-ofed-check -c 8
EOF_TREX_SUMMARY

  log "TRex setup complete"
  cat "${TREX_DIR}/automation/preof/host-summary.txt"
}

main() {
  require_root
  parse_args "$@"

  case "${ROLE}" in
    receiver) setup_receiver ;;
    upf) setup_upf ;;
    trex) setup_trex ;;
  esac
}

main "$@"


#!/usr/bin/env bash
set -Eeuo pipefail

# Unified setup for the PREOF/FRER-inspired BESS-UPF + TRex + receiver testbed.
# Roles:
#   --setup upf       MICH, BESS-UPF DPDK host
#   --setup trex      UCSD, TRex traffic generator host
#   --setup receiver  FIU, Linux receiver/deduplicator host
#
# Defaults follow the validated README addressing plan:
#   N3/control side: TRex 192.168.70.2 -> UPF 192.168.70.1
#   N6/receiver side: UPF 192.168.80.1 -> receiver 192.168.80.2
#   PFCP/control side: TRex 192.168.90.2 -> UPF 192.168.90.1
#
# Typical usage for the current FABRIC topology discovered on 2026-05-04:
#   receiver FIU: sudo ./setup_preof_testbed_fabric_v2.sh --setup receiver
#   UPF MICH:     sudo ./setup_preof_testbed_fabric_v2.sh --setup upf
#   TRex UCSD:    sudo ./setup_preof_testbed_fabric_v2.sh --setup trex
#
# Discovered default mapping:
#   UCSD/TRex    N3= enp7s0np0, PFCP/control= enp9s0
#   MICH/UPF     N3= enp8s0np0, N6= enp9s0np0, PFCP/control= enp7s0
#   FIU/Receiver N6= enp8s0np0
#
# Notes:
#   1. This script intentionally does NOT clone pfcpsim, because the patched repository/image is external.
#   2. For TRex, a one-port N3 configuration is generated by default. If your TRex build requires two ports,
#      pass --trex-port2-if IFACE and --trex-port2-dst-mac MAC.
#   3. The script flushes and assigns IP addresses on the interfaces passed to it.

ROLE=""

# Interface defaults are role-specific and are applied after --setup is parsed.
# They match the current FABRIC topology discovered on 2026-05-04.
N3_IF=""
N6_IF=""
CTRL_IF=""
TREX_PORT2_IF=""

# IP defaults.
UPF_N3_IP="192.168.70.1"
TREX_N3_IP="192.168.70.2"
UPF_N6_IP="192.168.80.1"
RECEIVER_N6_IP="192.168.80.2"
UPF_CTRL_IP="192.168.90.1"
TREX_CTRL_IP="192.168.90.2"

# MACs, can be supplied or discovered by ARP when possible.
# Defaults below match the current FABRIC topology discovered on 2026-05-04.
UPF_N3_MAC=""
RECEIVER_N6_MAC=""
TREX_PORT2_DST_MAC=""

# Software versions.
TREX_VERSION="v3.08"
TREX_TARBALL_URL="https://trex-tgn.cisco.com/trex/release/v3.08.tar.gz"
MLNX_OFED_URL="https://www.mellanox.com/downloads/ofed/MLNX_OFED-5.9-0.5.6.0/MLNX_OFED_LINUX-5.9-0.5.6.0-ubuntu22.04-x86_64.tgz"
MLNX_OFED_DIR="MLNX_OFED_LINUX-5.9-0.5.6.0-ubuntu22.04-x86_64"

HUGEPAGES="1024"
PERSIST_NETPLAN="false"
START_UPF="true"
INSTALL_OFED="true"

WORKDIR="/opt/preof-testbed"
BESS_WORKDIR="/opt/bess-upf"
TREX_DIR="/opt/trex/v3.08"

usage() {
  cat <<USAGE
Usage:
  sudo $0 --setup upf|trex|receiver [options]

Common options:
  --n3-if IFACE                 N3 traffic interface, role-specific default
  --n6-if IFACE                 N6 traffic interface, role-specific default
  --ctrl-if IFACE               PFCP/control interface, role-specific default
  --upf-n3-ip IP                default ${UPF_N3_IP}
  --trex-n3-ip IP               default ${TREX_N3_IP}
  --upf-n6-ip IP                default ${UPF_N6_IP}
  --receiver-n6-ip IP           default ${RECEIVER_N6_IP}
  --upf-ctrl-ip IP              default ${UPF_CTRL_IP}
  --trex-ctrl-ip IP             default ${TREX_CTRL_IP}
  --hugepages N                 default ${HUGEPAGES}
  --persist-netplan             write a simple netplan file for the selected role
  --skip-ofed                   skip MLNX OFED userspace installation

UPF-specific:
  --receiver-n6-mac MAC         receiver N6 MAC, used for static neighbor/route
  --no-start-upf                prepare images/configs but do not start BESS/pfcpiface

TRex-specific:
  --upf-n3-mac MAC              UPF N3 destination MAC for /etc/trex_cfg.yaml
  --trex-port2-if IFACE         optional second TRex port if your TRex requires paired ports
  --trex-port2-dst-mac MAC      destination MAC for optional second TRex port

Examples for the current topology:
  sudo $0 --setup receiver
  sudo $0 --setup upf
  sudo $0 --setup trex

Equivalent explicit form:
  sudo $0 --setup receiver --n6-if enp8s0np0
  sudo $0 --setup upf --n3-if enp8s0np0 --n6-if enp9s0np0 --ctrl-if enp7s0 --receiver-n6-mac 10:70:fd:c0:ef:40
  sudo $0 --setup trex --n3-if enp7s0np0 --ctrl-if enp9s0 --upf-n3-mac b8:ce:f6:19:09:32
USAGE
}

log() { echo "[preof-setup] $*"; }
warn() { echo "[preof-setup][WARN] $*" >&2; }
fatal() { echo "[preof-setup][ERROR] $*" >&2; exit 1; }

require_root() {
  if [[ "${EUID}" -ne 0 ]]; then
    fatal "Run as root, for example: sudo $0 ..."
  fi
}

apply_role_defaults() {
  case "${ROLE}" in
    receiver)
      : "${N6_IF:=enp8s0np0}"
      # Receiver N6 observed on FIU:
      #   enp8s0np0 MAC 10:70:fd:c0:ef:40, PCI 0000:08:00.0
      ;;
    upf)
      : "${N3_IF:=enp8s0np0}"
      : "${N6_IF:=enp9s0np0}"
      : "${CTRL_IF:=enp7s0}"
      : "${RECEIVER_N6_MAC:=10:70:fd:c0:ef:40}"
      # UPF observed on MICH:
      #   N3/access     enp8s0np0 MAC b8:ce:f6:19:09:32, PCI 0000:08:00.0
      #   N6/core       enp9s0np0 MAC b8:ce:f6:19:09:33, PCI 0000:09:00.0
      #   PFCP/control  enp7s0    MAC 02:0b:7f:65:7b:51, PCI 0000:07:00.0
      ;;
    trex)
      : "${N3_IF:=enp7s0np0}"
      : "${CTRL_IF:=enp9s0}"
      : "${UPF_N3_MAC:=b8:ce:f6:19:09:32}"
      # TRex observed on UCSD:
      #   N3            enp7s0np0 MAC 10:70:fd:c0:ef:a0, PCI 0000:07:00.0
      #   PFCP/control  enp9s0    MAC 16:e7:68:5c:0e:b8, PCI 0000:09:00.0
      ;;
  esac
}

print_effective_topology() {
  log "Effective topology for role ${ROLE}"
  case "${ROLE}" in
    receiver)
      echo "  Receiver N6: ${N6_IF} -> ${RECEIVER_N6_IP}/24"
      ;;
    upf)
      echo "  UPF N3/access:     ${N3_IF} -> ${UPF_N3_IP}/24"
      echo "  UPF N6/core:       ${N6_IF} -> ${UPF_N6_IP}/24"
      echo "  UPF PFCP/control:  ${CTRL_IF} -> ${UPF_CTRL_IP}/24"
      echo "  Receiver N6 MAC:   ${RECEIVER_N6_MAC:-auto-discover}"
      ;;
    trex)
      echo "  TRex N3:           ${N3_IF} -> ${TREX_N3_IP}/24"
      echo "  TRex PFCP/control: ${CTRL_IF} -> ${TREX_CTRL_IP}/24"
      echo "  UPF N3 MAC:        ${UPF_N3_MAC:-auto-discover}"
      ;;
  esac
}

parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --setup) ROLE="${2:-}"; shift 2 ;;
      --n3-if) N3_IF="${2:-}"; shift 2 ;;
      --n6-if) N6_IF="${2:-}"; shift 2 ;;
      --ctrl-if) CTRL_IF="${2:-}"; shift 2 ;;
      --trex-port2-if) TREX_PORT2_IF="${2:-}"; shift 2 ;;
      --trex-port2-dst-mac) TREX_PORT2_DST_MAC="${2:-}"; shift 2 ;;
      --upf-n3-ip) UPF_N3_IP="${2:-}"; shift 2 ;;
      --trex-n3-ip) TREX_N3_IP="${2:-}"; shift 2 ;;
      --upf-n6-ip) UPF_N6_IP="${2:-}"; shift 2 ;;
      --receiver-n6-ip) RECEIVER_N6_IP="${2:-}"; shift 2 ;;
      --upf-ctrl-ip) UPF_CTRL_IP="${2:-}"; shift 2 ;;
      --trex-ctrl-ip) TREX_CTRL_IP="${2:-}"; shift 2 ;;
      --upf-n3-mac) UPF_N3_MAC="${2:-}"; shift 2 ;;
      --receiver-n6-mac) RECEIVER_N6_MAC="${2:-}"; shift 2 ;;
      --hugepages) HUGEPAGES="${2:-}"; shift 2 ;;
      --persist-netplan) PERSIST_NETPLAN="true"; shift ;;
      --skip-ofed) INSTALL_OFED="false"; shift ;;
      --no-start-upf) START_UPF="false"; shift ;;
      -h|--help) usage; exit 0 ;;
      *) fatal "Unknown argument: $1" ;;
    esac
  done

  case "${ROLE}" in
    upf|trex|receiver) ;;
    *) usage; fatal "Missing or invalid --setup role. Use upf, trex, or receiver." ;;
  esac

  apply_role_defaults
  print_effective_topology
}


load_rdma_modules() {
  log "Loading RDMA and Mellanox modules"
  modprobe ib_uverbs || warn "Could not load ib_uverbs"
  modprobe rdma_ucm || warn "Could not load rdma_ucm"
  modprobe mlx5_ib || warn "Could not load mlx5_ib"
  ldconfig || true
}

validate_rdma_stack() {
  log "Validating RDMA and mlx5 userspace"
  if [[ -e /lib/x86_64-linux-gnu/libmlx5.so.1 ]]; then
    strings /lib/x86_64-linux-gnu/libmlx5.so.1 | grep -q MLX5_1.24 \
      && log "MLX5_1.24 symbol found in libmlx5.so.1" \
      || warn "MLX5_1.24 symbol not found in /lib/x86_64-linux-gnu/libmlx5.so.1"
  else
    warn "/lib/x86_64-linux-gnu/libmlx5.so.1 not found"
  fi

  if [[ -d /dev/infiniband ]]; then
    ls -l /dev/infiniband || true
  else
    warn "/dev/infiniband not found"
  fi

  if command -v ibv_devinfo >/dev/null 2>&1; then
    ibv_devinfo || warn "ibv_devinfo returned a non-zero status"
  else
    warn "ibv_devinfo not installed"
  fi
}

basic_reachability_tests() {
  log "Running basic reachability checks for role ${ROLE}"

  case "${ROLE}" in
    receiver)
      ip -br addr show "${N6_IF}" || true
      ping -c 2 -W 1 "${UPF_N6_IP}" || warn "Receiver could not ping UPF N6 ${UPF_N6_IP}. This can be normal if UPF is not configured yet."
      ;;
    upf)
      ip -br addr show "${N3_IF}" "${N6_IF}" "${CTRL_IF}" || true
      ping -c 2 -W 1 "${TREX_N3_IP}" || warn "UPF could not ping TRex N3 ${TREX_N3_IP}. This can be normal if TRex is not configured yet or the interface is DPDK-owned."
      ping -c 2 -W 1 "${RECEIVER_N6_IP}" || warn "UPF could not ping receiver N6 ${RECEIVER_N6_IP}. This can be normal if receiver is not configured yet."
      ping -c 2 -W 1 "${TREX_CTRL_IP}" || warn "UPF could not ping TRex PFCP/control ${TREX_CTRL_IP}. This can be normal if TRex is not configured yet."
      ;;
    trex)
      ip -br addr show "${N3_IF}" "${CTRL_IF}" || true
      ping -c 2 -W 1 "${UPF_N3_IP}" || warn "TRex could not ping UPF N3 ${UPF_N3_IP}. This can be normal if UPF is not configured yet."
      ping -c 2 -W 1 "${UPF_CTRL_IP}" || warn "TRex could not ping UPF PFCP/control ${UPF_CTRL_IP}. This can be normal if UPF is not configured yet."
      ;;
  esac
}

install_ofed_userspace() {
  [[ "${INSTALL_OFED}" == "true" ]] || { log "Skipping MLNX OFED installation"; return; }

  log "Installing MLNX OFED userspace"
  mkdir -p /tmp/preof-ofed
  cd /tmp/preof-ofed
  if [[ ! -f "${MLNX_OFED_URL##*/}" ]]; then
    wget -q --show-progress "${MLNX_OFED_URL}"
  fi
  rm -rf "${MLNX_OFED_DIR}"
  tar xzf "${MLNX_OFED_URL##*/}"
  cd "${MLNX_OFED_DIR}"
  ./mlnxofedinstall --user-space-only --without-fw-update || warn "MLNX OFED installer returned a non-zero status. Check logs above."
  ldconfig

  modprobe ib_uverbs || true
  modprobe rdma_ucm || true
  modprobe mlx5_ib || true

  log "OFED validation output"
  strings /lib/x86_64-linux-gnu/libmlx5.so.1 2>/dev/null | grep MLX5_1.24 || warn "MLX5_1.24 not found in libmlx5.so.1"
  ls -l /dev/infiniband 2>/dev/null || warn "/dev/infiniband not present"
}

configure_hugepages() {
  log "Configuring hugepages: ${HUGEPAGES}"
  mkdir -p /dev/hugepages
  mount -t hugetlbfs nodev /dev/hugepages 2>/dev/null || true
  sysctl -w vm.nr_hugepages="${HUGEPAGES}"
  echo "vm.nr_hugepages=${HUGEPAGES}" > /etc/sysctl.d/90-preof-hugepages.conf
  grep -i Huge /proc/meminfo || true
}

interface_exists() {
  ip link show dev "$1" >/dev/null 2>&1
}

configure_ip() {
  local iface="$1"
  local ip_cidr="$2"
  local label="$3"

  interface_exists "${iface}" || fatal "Interface ${iface} for ${label} not found. Use --n3-if/--n6-if/--ctrl-if with the real Linux name."

  log "Configuring ${label}: ${iface} -> ${ip_cidr}"
  ip link set "${iface}" up
  ip addr flush dev "${iface}"
  ip addr add "${ip_cidr}" dev "${iface}"
  ip link set "${iface}" mtu 1500

  # For reproducible software tests, disabling offloads can make captures easier to interpret.
  ethtool -K "${iface}" gro off gso off tso off rx off tx off 2>/dev/null || true
  ip -br addr show "${iface}"
}

iface_mac() {
  cat "/sys/class/net/$1/address"
}

iface_pci_short() {
  local iface="$1"
  local pci
  pci="$(basename "$(readlink -f "/sys/class/net/${iface}/device")")"
  echo "${pci#0000:}"
}

persist_netplan_for_role() {
  [[ "${PERSIST_NETPLAN}" == "true" ]] || return

  log "Writing netplan persistence for role ${ROLE}"
  case "${ROLE}" in
    receiver)
      cat > /etc/netplan/60-preof-testbed.yaml <<EOF_NETPLAN
network:
  version: 2
  ethernets:
    ${N6_IF}:
      addresses: [${RECEIVER_N6_IP}/24]
      mtu: 1500
EOF_NETPLAN
      ;;
    upf)
      cat > /etc/netplan/60-preof-testbed.yaml <<EOF_NETPLAN
network:
  version: 2
  ethernets:
    ${N3_IF}:
      addresses: [${UPF_N3_IP}/24]
      mtu: 1500
    ${N6_IF}:
      addresses: [${UPF_N6_IP}/24]
      mtu: 1500
    ${CTRL_IF}:
      addresses: [${UPF_CTRL_IP}/24]
      mtu: 1500
EOF_NETPLAN
      ;;
    trex)
      cat > /etc/netplan/60-preof-testbed.yaml <<EOF_NETPLAN
network:
  version: 2
  ethernets:
    ${N3_IF}:
      addresses: [${TREX_N3_IP}/24]
      mtu: 1500
    ${CTRL_IF}:
      addresses: [${TREX_CTRL_IP}/24]
      mtu: 1500
EOF_NETPLAN
      ;;
  esac
  netplan apply || warn "netplan apply failed. The live ip configuration was already applied."
}

discover_neighbor_mac() {
  local iface="$1"
  local ip="$2"
  local supplied_mac="$3"

  if [[ -n "${supplied_mac}" ]]; then
    echo "${supplied_mac}"
    return
  fi

  ping -c 1 -W 1 -I "${iface}" "${ip}" >/dev/null 2>&1 || true
  ip neigh show "${ip}" dev "${iface}" | awk '{print $5}' | head -n1
}

setup_receiver() {
  apt_install_common
  install_ofed_userspace
  load_rdma_modules
  validate_rdma_stack
  configure_hugepages

  configure_ip "${N6_IF}" "${RECEIVER_N6_IP}/24" "receiver N6"
  persist_netplan_for_role
  basic_reachability_tests

  log "Installing Python packages useful for receiver-side dedup experiments"
  python3 -m pip install --upgrade pip >/dev/null 2>&1 || true
  python3 -m pip install scapy pandas >/dev/null 2>&1 || true

  mkdir -p "${WORKDIR}/receiver"
  cat > "${WORKDIR}/receiver/README.txt" <<EOF_RX
Receiver host prepared.

N6 interface: ${N6_IF}
N6 IP:        ${RECEIVER_N6_IP}
N6 MAC:       $(iface_mac "${N6_IF}")

Use this MAC on the UPF if ARP discovery is not available:
  --receiver-n6-mac $(iface_mac "${N6_IF}")

Suggested capture check:
  sudo tcpdump -i ${N6_IF} -nn udp port 5555
EOF_RX

  log "Receiver setup complete"
  cat "${WORKDIR}/receiver/README.txt"
}

